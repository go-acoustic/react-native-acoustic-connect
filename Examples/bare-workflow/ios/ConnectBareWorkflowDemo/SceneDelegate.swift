import UIKit
import React
import React_RCTAppDelegate

// Apps built with the iOS 27 SDK must use the scene life cycle, or iOS refuses
// to launch them. The window and the React Native root view live here; the
// factory is still created in AppDelegate.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard
      let windowScene = scene as? UIWindowScene,
      let appDelegate = UIApplication.shared.delegate as? AppDelegate
    else { return }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window

    appDelegate.reactNativeFactory?.startReactNative(
      withModuleName: "ConnectBareWorkflowDemo",
      in: window,
      launchOptions: nil
    )
  }
}
